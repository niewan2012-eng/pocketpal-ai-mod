#!/usr/bin/env python3
"""Regenerate the Kokoro Mandarin G2P tables and their test fixture.

The zh voice embeddings in onnx-community/Kokoro-82M-v1.0-ONNX were trained on
misaki's pinyin->IPA output. `src/services/tts/engines/kokoro/zh/pinyinIpaTables.ts`
is a transcription of misaki/transcription.py (MIT, itself adapted from
stefantaubert/pinyin-to-ipa), and `__tests__/expectedSyllables.ts` is misaki's own
output for a representative syllable set — kept next to the tables so the port can
be checked against the reference instead of against itself.

Usage (needs `pip install pypinyin ordered-set`):

    python scripts/gen-kokoro-zh-tables.py

Nothing else in the app depends on Python; this runs by hand when the tables or
the reference implementation move.
"""

import ast
import io
import json
import os
import re
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MISAKI_TRANSCRIPTION = (
    'https://raw.githubusercontent.com/hexgrad/misaki/main/misaki/transcription.py'
)
TABLES_OUT = os.path.join(
    REPO, 'src/services/tts/engines/kokoro/zh/pinyinIpaTables.ts'
)
FIXTURE_OUT = os.path.join(
    REPO, 'src/services/tts/engines/kokoro/zh/__tests__/expectedSyllables.ts'
)

# The fixture is a representative slice; the full product is ~4000 syllables,
# which is more review noise than signal in a repo.
FIXTURE_SYLLABLES = [
    'ni3', 'hao3', 'shi4', 'jie4', 'jin1', 'tian1', 'qi4', 'hen3', 'wo3',
    'men5', 'chu1', 'qu4', 'san4', 'bu4', 'sui4', 'ba5', 'ma5',
    'zhi1', 'chi2', 'si1', 'er2',
    'lü4', 'lüe4', 'nü3', 'ju2', 'xu1', 'yu2', 'yue4', 'yuan2', 'yun2',
    'wu3', 'wa1', 'wen2', 'wang2', 'weng1', 'liu2', 'gui4', 'gun3', 'jun1',
    'ai4', 'ao3', 'ou4', 'an1', 'en1', 'ang2', 'eng1', 'ong1',
    'ia1', 'iao1', 'ie1', 'iou1', 'ian1', 'in1', 'iang1', 'ing1', 'iong1',
    'ua1', 'uo1', 'uai1', 'uei1', 'uan1', 'uen1', 'uang1', 'ü1', 'üe1',
]

TABLE_NAMES = [
    'INITIAL_MAPPING',
    'SYLLABIC_CONSONANT_MAPPINGS',
    'INTERJECTION_MAPPINGS',
    'FINAL_MAPPING',
    'FINAL_MAPPING_AFTER_ZH_CH_SH_R',
    'FINAL_MAPPING_AFTER_Z_C_S',
]

# pypinyin TONE3 digit -> Chao tone letters, exactly as misaki's TONE_MAPPING.
TONE_MAPPING = {
    1: '\u02e5',
    2: '\u02e7\u02e5',
    3: '\u02e7\u02e9\u02e7',
    4: '\u02e5\u02e9',
    5: '',
}


def fetch_transcription(path):
    if os.path.exists(path) and os.path.getsize(path) > 0:
        return
    subprocess.check_call(['curl', '-fsSL', MISAKI_TRANSCRIPTION, '-o', path])


def parse_tables(src):
    tables = {}
    for name in TABLE_NAMES:
        m = re.search(rf'^{name}: [^=]+= (\{{)', src, re.M)
        if not m:
            sys.exit(f'cannot find {name} in transcription.py')
        start = m.start(1)
        depth = 0
        end = None
        for i in range(start, len(src)):
            if src[i] == '{':
                depth += 1
            elif src[i] == '}':
                depth -= 1
                if depth == 0:
                    end = i + 1
                    break
        literal = re.sub(r'#.*', '', src[start:end])
        tables[name] = ast.literal_eval(literal)
    tables['TONE_MAPPING'] = TONE_MAPPING
    return tables


def ts_key(key):
    return "'%s'" % key.replace("'", "\\'")


def ts_value(value):
    if isinstance(value, str):
        return "'%s'" % value.replace('\\', '\\\\').replace("'", "\\'")
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return '[' + ', '.join(
            '[' + ', '.join(ts_value(piece) for piece in variant) + ']'
            for variant in value
        ) + ']'
    raise TypeError(type(value))


def write_tables(tables):
    lines = [
        '/**',
        " * Pinyin -> IPA tables for Kokoro's Mandarin voices.",
        ' *',
        ' * Ported verbatim from misaki/transcription.py (the G2P behind the zh voice',
        ' * pack these embeddings were trained with: zf_…/zm_… in',
        ' * onnx-community/Kokoro-82M-v1.0-ONNX). Keeping the tables identical matters',
        ' * more than looking tidy: any deviation is a phoneme the model never saw.',
        ' *',
        ' * Each pinyin initial/final maps to a list of *variants*, each variant a list',
        ' * of pieces where the literal "0" marks where the tone letter goes. misaki',
        ' * takes the first variant; so do we.',
        ' *',
        ' * Generated by scripts/gen-kokoro-zh-tables.py — do not edit by hand.',
        ' */',
        '',
        'export type PhonemeVariant = string[];',
        'export type PhonemeTable = Record<string, PhonemeVariant[]>;',
        '',
    ]
    for name, table in tables.items():
        if name == 'TONE_MAPPING':
            lines.append('/** Chao tone letters, indexed by pinyin tone number (5 = neutral). */')
            lines.append('export const TONE_MAPPING: Record<number, string> = {')
            for key in sorted(table):
                lines.append('  %d: %s,' % (key, ts_value(table[key])))
            lines += ['};', '']
            continue
        lines.append('export const %s: PhonemeTable = {' % name)
        for key, value in table.items():
            lines.append('  %s: %s,' % (ts_key(key), ts_value(value)))
        lines += ['};', '']
    io.open(TABLES_OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', TABLES_OUT)


def retone(ipa):
    return (ipa
            .replace('\u02e7\u02e9\u02e7', '\u2193')
            .replace('\u02e7\u02e5', '\u2197')
            .replace('\u02e5\u02e9', '\u2198')
            .replace('\u02e5', '\u2192')
            .replace('\u027b\u0329', '\u0268')
            .replace('\u0279\u0329', '\u0268')
            .replace('\u0329', '')
            .replace('\u032f', ''))


def write_fixture(transcription_path):
    import importlib.util

    spec = importlib.util.spec_from_file_location('tr', transcription_path)
    tr = importlib.util.module_from_spec(spec)
    sys.modules['tr'] = tr
    spec.loader.exec_module(tr)

    lines = [
        '/**',
        " * Expected IPA for a representative syllable set, taken from misaki's own",
        ' * pinyin_to_ipa (see scripts/gen-kokoro-zh-tables.py). Regenerate alongside',
        ' * the tables: these values are the training G2P output, not invented here.',
        ' */',
        '',
        'export const EXPECTED_SYLLABLES: Record<string, string> = {',
    ]
    written = 0
    for syllable in FIXTURE_SYLLABLES:
        try:
            ipa = ''.join(retone(piece) for piece in tr.pinyin_to_ipa(syllable)[0])
        except Exception:
            continue
        lines.append("  '%s': '%s'," % (syllable, ipa))
        written += 1
    lines += ['};', '']
    io.open(FIXTURE_OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('wrote', FIXTURE_OUT, '(%d syllables)' % written)


def main():
    work = tempfile.mkdtemp(prefix='kokoro-zh-')
    transcription = os.path.join(work, 'transcription.py')
    fetch_transcription(transcription)
    src = io.open(transcription, encoding='utf-8').read()
    write_tables(parse_tables(src))
    write_fixture(transcription)


if __name__ == '__main__':
    main()
